function createRequestId(): string {
  return crypto.randomUUID();
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

function utf8ByteLength(value: string): number {
  return new TextEncoder().encode(value).byteLength;
}

/**
 * Defense in depth for a compromised native host: the Rust implementation
 * caps these responses at 120 KiB, while the extension refuses any equivalent
 * admitted page at or above Chrome native messaging's 128 KiB safety bound.
 */
function isBoundedTranscriptSegmentResponse(
  requestId: string | undefined,
  jobId: string,
  segments: readonly NativeTranscriptSegment[],
  nextCursor: number | undefined
): boolean {
  const response: Record<string, unknown> = {
    response: "transcript_segments",
    job_id: jobId,
    segments
  };
  if (requestId !== undefined) {
    response.request_id = requestId;
  }
  if (nextCursor !== undefined) {
    response.next_cursor = nextCursor;
  }
  return utf8ByteLength(JSON.stringify(response)) < MAX_TRANSCRIPT_SEGMENT_RESPONSE_BYTES;
}

/**
 * Existing subtitle pages are limited by the native host, but enforce the
 * native-messaging frame boundary again before cue text reaches extension
 * memory. This also covers completed transcript cue retrieval used for export.
 */
function isBoundedSubtitleCueResponse(
  requestId: string | undefined,
  jobId: string,
  cues: readonly NativeSubtitleCue[],
  nextCursor: number | undefined
): boolean {
  const response: Record<string, unknown> = {
    response: "subtitle_cues",
    job_id: jobId,
    cues
  };
  if (requestId !== undefined) {
    response.request_id = requestId;
  }
  if (nextCursor !== undefined) {
    response.next_cursor = nextCursor;
  }
  return utf8ByteLength(JSON.stringify(response)) < MAX_SUBTITLE_CUE_RESPONSE_BYTES;
}
