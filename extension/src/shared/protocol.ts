export function isPopupRequest(value: unknown): value is PopupRequest {
  if (!isRecord(value) || typeof value.type !== "string") {
    return false;
  }
  switch (value.type) {
    case "popup.detect-media":
    case "popup.get-jobs":
    case "popup.get-engine-state":
      return true;
    case "popup.get-transcript":
      return (
        typeof value.jobId === "string" &&
        value.jobId.length > 0 &&
        value.jobId.length <= 256 &&
        (value.cursor === undefined || isNativeCursor(value.cursor)) &&
        (value.limit === undefined || isTranscriptSegmentPageLimit(value.limit))
      );
    case "popup.export-transcript":
      return (
        typeof value.jobId === "string" &&
        value.jobId.length > 0 &&
        value.jobId.length <= 256 &&
        isTranscriptExportFormat(value.format)
      );
    case "popup.stop-job":
      return typeof value.jobId === "string" && value.jobId.length > 0;
    case "popup.start-job":
      return (
        (value.jobKind === "subtitle" || value.jobKind === "transcript") &&
        (value.pastedUrl === undefined || typeof value.pastedUrl === "string") &&
        (value.forceGenerate === undefined || typeof value.forceGenerate === "boolean")
      );
    default:
      return false;
  }
}

export function parseEngineConnectionStateUpdate(value: unknown): EngineConnectionStateUpdate | null {
  if (!isRecord(value) || value.type !== "engine.connection-state") {
    return null;
  }
  const payload = parseEngineConnectionState(value.payload);
  return payload ? { type: "engine.connection-state", payload } : null;
}

export function isEngineConnectionStateUpdate(value: unknown): value is EngineConnectionStateUpdate {
  return parseEngineConnectionStateUpdate(value) !== null;
}

export function isContentRequest(value: unknown): value is ContentRequest {
  if (!isRecord(value) || typeof value.type !== "string") {
    return false;
  }
  switch (value.type) {
    case "content.get-media":
    case "content.get-network-media-candidates":
      return true;
    case "content.start-overlay":
      return (
        typeof value.mediaId === "string" &&
        (value.mode === "existing" || value.mode === "generated") &&
        (value.cues === undefined || isSubtitleCueArray(value.cues)) &&
        (value.visibleCaptionFallback === undefined || typeof value.visibleCaptionFallback === "boolean")
      );
    case "content.set-overlay-cues":
      return typeof value.mediaId === "string" && isSubtitleCueArray(value.cues);
    case "content.append-overlay-cues":
      return typeof value.mediaId === "string" && isSubtitleCueArray(value.cues, 200);
    case "content.start-playback-observation":
      return typeof value.mediaId === "string" && value.mediaId.length > 0 && isNativeJobId(value.jobId);
    case "content.stop-playback-observation":
      return (
        (value.mediaId === undefined || typeof value.mediaId === "string") &&
        (value.jobId === undefined || isNativeJobId(value.jobId))
      );
    case "content.stop-overlay":
      return value.mediaId === undefined || typeof value.mediaId === "string";
    default:
      return false;
  }
}

export function isContentPlaybackUpdate(value: unknown): value is ContentPlaybackUpdate {
  return (
    isRecord(value) &&
    value.type === "content.playback-update" &&
    isNativeJobId(value.jobId) &&
    typeof value.mediaId === "string" &&
    value.mediaId.length > 0 &&
    isPlaybackPositionMs(value.positionMs) &&
    isPlaybackRateMilli(value.playbackRateMilli) &&
    typeof value.isPaused === "boolean" &&
    isSeekGeneration(value.seekGeneration)
  );
}

/** Only direct HTTPS URLs are valid native input. Reject data/blob/file URLs and embedded credentials. */
export function sanitizeDirectMediaUrl(value: unknown): string | null {
  if (typeof value !== "string" || value.length > 16_384) {
    return null;
  }
  try {
    const url = new URL(value);
    if (url.protocol !== "https:" || url.username || url.password) {
      return null;
    }
    url.hash = "";
    return url.href;
  } catch {
    return null;
  }
}

/**
 * Converts a safe local file URL into an absolute native filesystem path.
 * Remote/UNC authorities, ambiguous double-slash paths, queries, controls,
 * and non-absolute paths are rejected. A fragment is intentionally ignored:
 * it is not part of the filesystem path.
 */
export function sanitizeLocalFileUrl(value: unknown): string | null {
  if (typeof value !== "string" || value.length === 0 || value.length > 16_384) {
    return null;
  }
  try {
    const url = new URL(value);
    if (url.protocol !== "file:" || url.host !== "" || url.search !== "") {
      return null;
    }
    // A double-slash pathname can be interpreted as a network/UNC location on
    // Windows even when URL parsing did not expose an authority component.
    if (url.pathname.startsWith("//") || /%2f|%5c/i.test(url.pathname)) {
      return null;
    }
    const pathname = decodeURIComponent(url.pathname);
    if (pathname.startsWith("//")) {
      return null;
    }
    const windowsPath = /^\/([a-z]):\/(.*)$/i.exec(pathname);
    const path = windowsPath ? `${windowsPath[1] ?? ""}:\\${(windowsPath[2] ?? "").replaceAll("/", "\\")}` : pathname;
    return sanitizeLocalFilePath(path);
  } catch {
    return null;
  }
}

/** True only for a safe, local non-UNC file document URL. */
export function isSafeLocalFilePageUrl(value: unknown): boolean {
  return sanitizeLocalFileUrl(value) !== null;
}

/**
 * Validates an already-decoded local path before native-message serialization.
 * It deliberately accepts only absolute POSIX paths or drive-rooted Windows
 * paths and never accepts UNC/device paths.
 */
export function sanitizeLocalFilePath(value: unknown): string | null {
  if (typeof value !== "string" || value.length === 0 || value.length > 32_768) {
    return null;
  }
  if (/[\x00-\x1f\x7f]/.test(value) || value.trim().length === 0) {
    return null;
  }
  if (value.startsWith("\\\\") || value.startsWith("//")) {
    return null;
  }
  const isDriveRootedWindowsPath = /^[a-z]:[\\/]/i.test(value);
  const isPosixAbsolutePath = value.startsWith("/") && !value.startsWith("//");
  return isDriveRootedWindowsPath || isPosixAbsolutePath ? value : null;
}

