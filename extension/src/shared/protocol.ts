export function createNativeStartRequest(
  payload: NativeStartJobPayload,
  requestId = createRequestId()
): NativeStartRequest {
  const hints: { duration_ms?: number } = {};
  if (payload.source.durationSeconds !== undefined) {
    hints.duration_ms = Math.max(0, Math.round(payload.source.durationSeconds * 1_000));
  }
  const source = nativeSourceFromStartPayload(payload.source);
  const settings: NativeStartRequest["job"]["settings"] = {
    force_generate_with_subtitler: payload.forceGenerateWithSubtitler === true,
    processing_preference: "local_only",
    speaker_diarization: false
  };
  if (payload.jobKind === "subtitle" && payload.initialPlayback) {
    settings.initial_playback = {
      position_ms: requirePlaybackPositionMs(Math.round(payload.initialPlayback.positionSeconds * 1_000)),
      playback_rate_milli: 1_000,
      is_paused: requireBoolean(payload.initialPlayback.isPaused, "initial playback paused state")
    };
  }
  return {
    request_id: requireNativeRequestId(requestId),
    command: "start",
    job: {
      client_job_id: payload.jobId,
      kind: payload.jobKind === "transcript" ? "full_transcript" : "subtitle_generation",
      media: {
        source,
        hints
      },
      settings
    }
  };
}

function nativeSourceFromStartPayload(source: NativeStartSource): NativeStartRequest["job"]["media"]["source"] {
  if (source.kind === "page") {
    const pageUrl = sanitizeDirectMediaUrl(source.pageUrl);
    if (!pageUrl) {
      throw new Error("invalid recording page URL");
    }
    return { kind: "page", page_url: pageUrl };
  }
  if (source.kind === "direct_url") {
    const mediaUrl = sanitizeDirectMediaUrl(source.mediaUrl);
    if (!mediaUrl) {
      throw new Error("invalid direct media URL");
    }
    return { kind: "direct_url", media_url: mediaUrl };
  }
  const path = sanitizeLocalFilePath(source.path);
  if (!path) {
    throw new Error("invalid local media path");
  }
  return { kind: "local_file", path };
}

